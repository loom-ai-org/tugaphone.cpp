"""Generate src/unicode_nfd.inc from the running Python's Unicode database.

The tokenizer calls unicodedata.normalize("NFD", ...) and
unicodedata.combining(...). The tables hold the full canonical decomposition
of every code point that has one (Hangul syllables excepted: the C++ code
decomposes them by the Unicode algorithm, as Python does) and the canonical
combining class of every code point whose class is not 0.

Usage: python -I tools/gen_unicode_nfd.py > src/unicode_nfd.inc
"""
import sys
import unicodedata

MAX = 0x110000
HANGUL_FIRST, HANGUL_LAST = 0xAC00, 0xD7A3


def main():
    w = sys.stdout.write
    w("// Generated by tools/gen_unicode_nfd.py; do not edit.\n")
    w(f"// Python {sys.version.split()[0]}, Unicode {unicodedata.unidata_version}.\n\n")
    decomp = []
    for cp in range(MAX):
        if 0xD800 <= cp <= 0xDFFF or HANGUL_FIRST <= cp <= HANGUL_LAST:
            continue
        ch = chr(cp)
        nfd = unicodedata.normalize("NFD", ch)
        if nfd != ch:
            decomp.append((cp, nfd))
    width = max(len(d) for _, d in decomp)
    w(f"static constexpr int kNfdWidth = {width};\n")
    w(f"static const NfdEntry kNfd[{len(decomp)}] = {{\n")
    for cp, nfd in decomp:
        padded = [ord(c) for c in nfd] + [0] * (width - len(nfd))
        w(f"  {{0x{cp:X}, {{{', '.join(f'0x{x:X}' for x in padded)}}}, {len(nfd)}}},\n")
    w("};\n\n")
    ranges = []
    for cp in range(MAX):
        ccc = unicodedata.combining(chr(cp)) if not 0xD800 <= cp <= 0xDFFF else 0
        if ccc and ranges and ranges[-1][1] == cp - 1 and ranges[-1][2] == ccc:
            ranges[-1][1] = cp
        elif ccc:
            ranges.append([cp, cp, ccc])
    w(f"static const CccRange kCcc[{len(ranges)}] = {{\n")
    for lo, hi, ccc in ranges:
        w(f"  {{0x{lo:X}, 0x{hi:X}, {ccc}}},\n")
    w("};\n")


if __name__ == "__main__":
    main()
